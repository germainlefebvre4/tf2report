#!/usr/bin/env bash
# Regenerate the authentic plan fixtures in testdata/plans/<engine>/, where <engine> is `terraform`
# (Terraform) or `opentofu` (OpenTofu).
#
# Each directory under testdata/scenarios/<name>/ describes one scenario:
#   plan/     configuration that is planned (may include a hand-written terraform.tfstate)
#   base/     (optional) configuration applied first, to build a prior state
#   flags     (optional) extra `plan` flags, e.g. -destroy, -replace=ADDR or -refresh=false
#   taint     (optional) one resource address per line, tainted after the base apply
#   engines   (optional) engines to run, one per line; default: all of them
#
# Scenarios either use the built-in `terraform_data` resource (no download at all) or pin exact provider
# versions and configure them with synthetic credentials, so planning needs no account and makes no call
# to a cloud API. Providers are downloaded from the registry of the engine on first use: expect roughly
# 1 GB for the cloud providers, kept in a cache directory between runs.
#
# The output is `show -json` verbatim, except that the non-deterministic `timestamp` is removed and UUIDs
# generated by the engine are replaced by a fixed value.
#
# Usage: scripts/gen-plans.sh [scenario ...]            (default: all scenarios)
#   ENGINES="terraform"     engines to run (default: "terraform opentofu"; one missing from PATH is skipped)
#   OUT_DIR=/tmp/x          parent of the engine directories (default: testdata/plans)
#   PLUGIN_CACHE=/path      provider cache (default: ~/.cache/tf2report/plugins)
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$root/testdata/scenarios"
out_root="${OUT_DIR:-$root/testdata/plans}"
engines="${ENGINES:-terraform opentofu}"
zero_uuid="00000000-0000-0000-0000-000000000000"

command -v jq >/dev/null || { echo "error: jq not found in PATH" >&2; exit 1; }

engine_bin() {
  case "$1" in
    terraform) echo "${TF_BIN:-terraform}" ;;
    opentofu) echo "${TOFU_BIN:-tofu}" ;;
    *) echo "error: unknown engine '$1' (want terraform or opentofu)" >&2; return 1 ;;
  esac
}

export TF_IN_AUTOMATION=1 TF_INPUT=0 CHECKPOINT_DISABLE=1
export TF_PLUGIN_CACHE_DIR="${PLUGIN_CACHE:-$HOME/.cache/tf2report/plugins}"
mkdir -p "$TF_PLUGIN_CACHE_DIR"

if [[ $# -gt 0 ]]; then
  scenarios=("$@")
else
  scenarios=()
  for d in "$src"/*/; do scenarios+=("$(basename "$d")"); done
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

for engine in $engines; do
  bin="$(engine_bin "$engine")"
  if ! command -v "$bin" >/dev/null; then
    echo "skip engine $engine: '$bin' not found in PATH" >&2
    continue
  fi
  out="$out_root/$engine"
  mkdir -p "$out"

  for name in "${scenarios[@]}"; do
    dir="$src/$name"
    [[ -d "$dir/plan" ]] || { echo "error: no scenario '$name' (missing $dir/plan)" >&2; exit 1; }
    if [[ -f "$dir/engines" ]] && ! grep -qx "$engine" "$dir/engines"; then
      continue
    fi

    w="$work/$engine/$name"
    mkdir -p "$w"
    cp -r "$dir/plan" "$w/plan"

    if [[ -d "$dir/base" ]]; then
      cp -r "$dir/base" "$w/base"
      (
        cd "$w/base"
        "$bin" init -no-color >/dev/null
        "$bin" apply -auto-approve -no-color >/dev/null
        if [[ -f "$dir/taint" ]]; then
          while IFS= read -r addr; do
            [[ -n "$addr" ]] && "$bin" taint -no-color "$addr" >/dev/null
          done <"$dir/taint"
        fi
      )
      cp "$w/base/terraform.tfstate" "$w/plan/terraform.tfstate"
    fi

    flags=()
    if [[ -f "$dir/flags" ]]; then
      read -r -a flags <"$dir/flags"
    fi

    (
      cd "$w/plan"
      "$bin" init -no-color >/dev/null
      "$bin" plan -no-color -out=tfplan "${flags[@]}" >/dev/null
      "$bin" show -json tfplan
    ) | jq --indent 2 'del(.timestamp)' \
      | sed -E "s/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/$zero_uuid/g" \
      >"$out/$name.json"

    echo "generated $engine/$name"
  done
done
