#!/usr/bin/env bash
# Regenerate the authentic Terraform plan fixtures in testdata/plans/terraform/.
#
# Each directory under testdata/scenarios/<name>/ describes one scenario:
#   base/   (optional) configuration applied first, to build a prior state
#   plan/   configuration that is planned on top of that state
#   flags   (optional) extra `terraform plan` flags, e.g. -destroy or -replace=ADDR
#   taint   (optional) one resource address per line, tainted after the base apply
#
# Only the built-in `terraform_data` resource is used, so the script needs no provider download,
# no network and no credentials. The output is `terraform show -json` verbatim, except that:
#   - the non-deterministic `timestamp` is removed;
#   - UUIDs generated by Terraform are replaced by a fixed value.
#
# Usage: scripts/gen-plans.sh [scenario ...]     (default: all scenarios)
#        TF_BIN=tofu scripts/gen-plans.sh        (use another binary)
#        OUT_DIR=/tmp/x scripts/gen-plans.sh     (write elsewhere)
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
tf="${TF_BIN:-terraform}"
src="$root/testdata/scenarios"
out="${OUT_DIR:-$root/testdata/plans/terraform}"
zero_uuid="00000000-0000-0000-0000-000000000000"

command -v "$tf" >/dev/null || { echo "error: '$tf' not found in PATH" >&2; exit 1; }
command -v jq >/dev/null || { echo "error: jq not found in PATH" >&2; exit 1; }

export TF_IN_AUTOMATION=1 TF_INPUT=0 CHECKPOINT_DISABLE=1

if [[ $# -gt 0 ]]; then
  scenarios=("$@")
else
  scenarios=()
  for d in "$src"/*/; do scenarios+=("$(basename "$d")"); done
fi

mkdir -p "$out"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

for name in "${scenarios[@]}"; do
  dir="$src/$name"
  [[ -d "$dir/plan" ]] || { echo "error: no scenario '$name' (missing $dir/plan)" >&2; exit 1; }

  w="$work/$name"
  mkdir -p "$w"
  cp -r "$dir/plan" "$w/plan"

  if [[ -d "$dir/base" ]]; then
    cp -r "$dir/base" "$w/base"
    (
      cd "$w/base"
      "$tf" init -no-color >/dev/null
      "$tf" apply -auto-approve -no-color >/dev/null
      if [[ -f "$dir/taint" ]]; then
        while IFS= read -r addr; do
          [[ -n "$addr" ]] && "$tf" taint -no-color "$addr" >/dev/null
        done <"$dir/taint"
      fi
    )
    cp "$w/base/terraform.tfstate" "$w/plan/terraform.tfstate"
  fi

  flags=()
  if [[ -f "$dir/flags" ]]; then
    read -r -a flags <"$dir/flags"
  fi

  (
    cd "$w/plan"
    "$tf" init -no-color >/dev/null
    "$tf" plan -no-color -out=tfplan "${flags[@]}" >/dev/null
    "$tf" show -json tfplan
  ) | jq --indent 2 'del(.timestamp)' \
    | sed -E "s/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/$zero_uuid/g" \
    >"$out/$name.json"

  echo "generated $name"
done
